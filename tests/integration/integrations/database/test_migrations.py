import asyncio
from pathlib import Path

import pytest
from alembic.runtime.migration import MigrationContext
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from fastapi import FastAPI
from sqlalchemy import Column, ForeignKey, MetaData, String, Table, insert, select, text

from fastapi_canon import Composition
from fastapi_canon.integrations.database import AlembicMigrations, Database


async def test_revision_upgrade_and_drift_check_preserve_existing_data(
    database: Database, metadata: MetaData, tmp_path: Path
) -> None:
    migrations = AlembicMigrations(directory=tmp_path / "migrations", metadata=metadata)
    migrations.initialize()
    table = metadata.tables["items"]
    references = Table(
        "item_references",
        metadata,
        Column("id", String(80), primary_key=True),
        Column("item_name", String(80), ForeignKey("items.name"), nullable=False),
    )
    async with asyncio.timeout(20), database.open_engine() as engine:
        await migrations.revision(engine, message="create items", autogenerate=True)
        with pytest.raises(RuntimeError, match="pending"):
            await migrations.require_current(engine)
        await migrations.upgrade(engine)
        await migrations.require_current(engine)
        initial_revision = ScriptDirectory(str(migrations.directory)).get_current_head()
        assert initial_revision is not None
        async with engine.begin() as connection:
            await connection.execute(insert(table).values(name="existing"))
            await connection.execute(
                insert(references).values(id="reference", item_name="existing")
            )
        table.c.name.type = String(120)
        table.append_column(
            Column("note", String(80), nullable=False, server_default="hello")
        )
        await migrations.revision(engine, message="add note", autogenerate=True)
        await migrations.upgrade(engine)
        await migrations.require_current(engine)
        await migrations.check(engine)
        async with engine.connect() as connection:
            assert (
                await connection.execute(select(table.c.name, table.c.note))
            ).one() == ("existing", "hello")
            assert await connection.scalar(select(references.c.item_name)) == "existing"
        await migrations.downgrade(engine, initial_revision)
        async with engine.connect() as connection:
            assert await connection.scalar(select(table.c.name)) == "existing"
            assert await connection.scalar(select(references.c.item_name)) == "existing"
            assert await connection.run_sync(
                lambda sync: MigrationContext.configure(sync).get_current_heads()
            ) == (initial_revision,)
            if engine.dialect.name == "sqlite":
                assert await connection.scalar(text("PRAGMA foreign_keys")) == 1
        with pytest.raises(RuntimeError, match="pending"):
            await migrations.require_current(engine)
        await migrations.upgrade(engine)
        await migrations.check(engine)
        async with engine.connect() as connection:
            assert (
                await connection.execute(select(table.c.name, table.c.note))
            ).one() == ("existing", "hello")
        table.append_column(Column("unmigrated", String(80)))
        with pytest.raises(AutogenerateDiffsDetected):
            await migrations.check(engine)
    revisions = list((tmp_path / "migrations/versions").glob("*.py"))
    assert len(revisions) == 2
    assert any(
        "batch_alter_table" in revision.read_text(encoding="utf-8")
        for revision in revisions
    )


async def test_failed_downgrade_rolls_back_schema_data_and_revision(
    database: Database, metadata: MetaData, tmp_path: Path
) -> None:
    migrations = AlembicMigrations(directory=tmp_path / "migrations", metadata=metadata)
    migrations.initialize()
    table = metadata.tables["items"]
    async with asyncio.timeout(20), database.open_engine() as engine:
        await migrations.revision(engine, message="initial", autogenerate=True)
        initial_revision = ScriptDirectory(str(migrations.directory)).get_current_head()
        assert initial_revision is not None
        await migrations.upgrade(engine)
        async with engine.begin() as connection:
            await connection.execute(insert(table).values(name="existing"))
        table.append_column(Column("note", String(80), server_default="hello"))
        revision_source = (
            "from alembic import op\n"
            "import sqlalchemy as sa\n"
            "revision = 'reject_downgrade'\n"
            f"down_revision = {initial_revision!r}\n"
            "def upgrade():\n"
            "    op.add_column('items', sa.Column('note', sa.String(80), "
            "server_default='hello'))\n"
            "def downgrade():\n"
            '    op.execute("DELETE FROM items")\n'
            "    with op.batch_alter_table('items') as batch:\n"
            "        batch.drop_column('note')\n"
            "    raise RuntimeError('downgrade rejected')\n"
        )
        revision_path = migrations.directory / "versions/reject_downgrade.py"
        revision_path.write_text(revision_source, encoding="utf-8")
        await migrations.upgrade(engine)
        with pytest.raises(RuntimeError, match="downgrade rejected"):
            await migrations.downgrade(engine, initial_revision)
        await migrations.require_current(engine)
        await migrations.check(engine)
        async with engine.connect() as connection:
            assert (
                await connection.execute(select(table.c.name, table.c.note))
            ).one() == ("existing", "hello")
            assert await connection.run_sync(
                lambda sync: MigrationContext.configure(sync).get_current_heads()
            ) == ("reject_downgrade",)
            if engine.dialect.name == "sqlite":
                assert await connection.scalar(text("PRAGMA foreign_keys")) == 1
    assert revision_path.read_text(encoding="utf-8") == revision_source


async def test_startup_checks_revisions_without_applying_migrations(
    tmp_path: Path, metadata: MetaData
) -> None:
    migrations = AlembicMigrations(directory=tmp_path / "migrations", metadata=metadata)
    database = Database(
        url=f"sqlite:///{tmp_path / 'startup.db'}", migrations=migrations
    )
    migrations.initialize()
    async with asyncio.timeout(15), database.open_engine() as engine:
        await migrations.revision(engine, message="initial", autogenerate=True)
    app = Composition(features=[database.feature]).build(FastAPI())
    async with asyncio.timeout(10):
        with pytest.raises(RuntimeError, match="pending"):
            async with app.router.lifespan_context(app):
                pytest.fail("Startup must reject pending migrations")
    async with asyncio.timeout(15), database.open_engine() as engine:
        with pytest.raises(RuntimeError, match="pending"):
            await migrations.require_current(engine)
        await migrations.upgrade(engine)
    ready = Composition(features=[database.feature]).build(FastAPI())
    async with asyncio.timeout(10), ready.router.lifespan_context(ready):
        assert ready.state.dishka_container is not None


def test_init_preserves_existing_revision_files(
    tmp_path: Path, metadata: MetaData
) -> None:
    migrations = AlembicMigrations(directory=tmp_path / "migrations", metadata=metadata)
    migrations.initialize()
    revision = tmp_path / "migrations/versions/existing.py"
    revision.write_text("# application-owned\n", encoding="utf-8")
    with pytest.raises(ValueError, match="empty"):
        migrations.initialize()
    assert revision.read_text(encoding="utf-8") == "# application-owned\n"


@pytest.mark.parametrize("missing", ["table", "column"])
async def test_revision_head_does_not_hide_missing_application_schema(
    database: Database, metadata: MetaData, tmp_path: Path, missing: str
) -> None:
    metadata.tables["items"].append_column(Column("note", String(80)))
    migrations = AlembicMigrations(directory=tmp_path / "migrations", metadata=metadata)
    migrations.initialize()
    async with asyncio.timeout(20), database.open_engine() as engine:
        await migrations.revision(engine, message="initial", autogenerate=True)
        await migrations.upgrade(engine)
        async with engine.begin() as connection:
            await connection.execute(
                text(
                    "DROP TABLE items"
                    if missing == "table"
                    else "ALTER TABLE items DROP COLUMN note"
                )
            )
        with pytest.raises(RuntimeError, match="schema is incomplete"):
            await migrations.require_current(engine)
        with pytest.raises(RuntimeError, match="forward repair migration"):
            await migrations.upgrade(engine)
