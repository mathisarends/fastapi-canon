import asyncio
from pathlib import Path

import pytest
from alembic.util.exc import AutogenerateDiffsDetected
from fastapi import FastAPI
from sqlalchemy import Column, ForeignKey, MetaData, String, Table, insert, select

from fastapi_canon import AlembicMigrations, Composition, Database


async def test_revision_upgrade_and_drift_check_preserve_existing_data(
    database: Database, metadata: MetaData, tmp_path: Path
) -> None:
    migrations = AlembicMigrations(directory=tmp_path / "migrations", metadata=metadata)
    migrations.initialize()
    table = metadata.tables["items"]
    references = Table(
        "item_references",
        metadata,
        Column("id", String(80), primary_key=True),
        Column("item_name", String(80), ForeignKey("items.name"), nullable=False),
    )
    async with asyncio.timeout(20), database.open_engine() as engine:
        await migrations.revision(engine, message="create items", autogenerate=True)
        with pytest.raises(RuntimeError, match="pending"):
            await migrations.require_current(engine)
        await migrations.upgrade(engine)
        await migrations.require_current(engine)
        async with engine.begin() as connection:
            await connection.execute(insert(table).values(name="existing"))
            await connection.execute(
                insert(references).values(id="reference", item_name="existing")
            )
        table.c.name.type = String(120)
        table.append_column(
            Column("note", String(80), nullable=False, server_default="hello")
        )
        await migrations.revision(engine, message="add note", autogenerate=True)
        await migrations.upgrade(engine)
        await migrations.require_current(engine)
        await migrations.check(engine)
        async with engine.connect() as connection:
            assert (
                await connection.execute(select(table.c.name, table.c.note))
            ).one() == ("existing", "hello")
            assert await connection.scalar(select(references.c.item_name)) == "existing"
        table.append_column(Column("unmigrated", String(80)))
        with pytest.raises(AutogenerateDiffsDetected):
            await migrations.check(engine)
    revisions = list((tmp_path / "migrations/versions").glob("*.py"))
    assert len(revisions) == 2
    assert any(
        "batch_alter_table" in revision.read_text(encoding="utf-8")
        for revision in revisions
    )


async def test_startup_checks_revisions_without_applying_migrations(
    tmp_path: Path, metadata: MetaData
) -> None:
    migrations = AlembicMigrations(directory=tmp_path / "migrations", metadata=metadata)
    database = Database(
        url=f"sqlite:///{tmp_path / 'startup.db'}", migrations=migrations
    )
    migrations.initialize()
    async with asyncio.timeout(15), database.open_engine() as engine:
        await migrations.revision(engine, message="initial", autogenerate=True)
    app = Composition(features=[database.feature]).apply(FastAPI())
    async with asyncio.timeout(10):
        with pytest.raises(RuntimeError, match="pending"):
            async with app.router.lifespan_context(app):
                pytest.fail("Startup must reject pending migrations")
    async with asyncio.timeout(15), database.open_engine() as engine:
        with pytest.raises(RuntimeError, match="pending"):
            await migrations.require_current(engine)
        await migrations.upgrade(engine)
    ready = Composition(features=[database.feature]).apply(FastAPI())
    async with asyncio.timeout(10), ready.router.lifespan_context(ready):
        assert ready.state.dishka_container is not None


def test_init_preserves_existing_revision_files(
    tmp_path: Path, metadata: MetaData
) -> None:
    migrations = AlembicMigrations(directory=tmp_path / "migrations", metadata=metadata)
    migrations.initialize()
    revision = tmp_path / "migrations/versions/existing.py"
    revision.write_text("# application-owned\n", encoding="utf-8")
    with pytest.raises(ValueError, match="empty"):
        migrations.initialize()
    assert revision.read_text(encoding="utf-8") == "# application-owned\n"
